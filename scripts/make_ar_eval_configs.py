"""Generate all-literal sample_eval yamls for the AR baseline: one per (checkpoint, temperature).

    python scripts/make_ar_eval_configs.py --train-config <ar_config> --run-glob 'outputs/<ar_run_name>_2*' \
        --steps 80000 --temperatures 1.0,0.9,0.8,0.7

Each yaml is the training config with only `mode` / `run_name` / `eval.checkpoint_path` /
`sampling.temperature` / `loader.eval_batch_size` / `sampling.num_sample_batches` changed (the same
convention as make_eval_configs.py for the flow model), so the model section always matches the
checkpoint, and every eval launches bare: python -m main --config-name <name>. Default cell: EMA
weights, 16 x 256 = 4096 samples, seed 1, 1023 sampled tokens after BOS, gpt2-large scorer (raw
weights when the run has `training.ema` 0).
run_name = eval_<train>_ck<step>_temp<T>[_n<N>][_s<seed>].
"""
import argparse
import glob
import os
import re
import sys

from omegaconf import OmegaConf

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def find_checkpoints(run_glob):
    """Map step -> absolute checkpoint dir over every run folder matching `run_glob`.

    The highest folder wins per step.
    """
    ckpts = {}
    for run_dir in sorted(glob.glob(os.path.join(REPO, run_glob))):
        for d in glob.glob(os.path.join(run_dir, 'checkpoints', 'checkpoint-*')):
            if not os.path.isfile(os.path.join(d, 'model.safetensors')):
                continue
            m = re.fullmatch(r'checkpoint-(\d+)', os.path.basename(d))
            # Skip suffixed folders (e.g. checkpoint-3000.incomplete)
            if not m:
                continue
            ckpts[int(m.group(1))] = os.path.abspath(d)
    return ckpts


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--train-config', required=True, help='the AR training config name (configs/<name>.yaml)')
    ap.add_argument('--run-glob', required=True, help="glob of the AR run dirs, e.g. 'outputs/<ar_run_name>_2*'")
    ap.add_argument('--steps', default='all', help="comma list of checkpoint steps, or 'all'")
    ap.add_argument('--temperatures', default='1.0', help='comma list of sampling temperatures')
    ap.add_argument('--eval-batch-size', type=int, default=256)
    ap.add_argument('--num-sample-batches', type=int, default=16)
    ap.add_argument('--seed', type=int, default=None, help='override the seed (adds _s<seed> to run_name)')
    ap.add_argument('--out-dir', default=os.path.join(REPO, 'configs'))
    ap.add_argument('--force', action='store_true')
    args = ap.parse_args()

    base_path = os.path.join(REPO, 'configs', f'{args.train_config}.yaml')
    if not os.path.isfile(base_path):
        sys.exit(f'no such training config: {base_path}')
    ckpts = find_checkpoints(args.run_glob)
    if not ckpts:
        sys.exit(f'no complete checkpoints under {args.run_glob}')
    steps = sorted(ckpts) if args.steps == 'all' else [int(s) for s in args.steps.split(',')]
    n_samples = args.num_sample_batches * args.eval_batch_size
    written = []
    for step in steps:
        if step not in ckpts:
            print(f'[skip] no complete checkpoint-{step}', file=sys.stderr)
            continue
        for temp in args.temperatures.split(','):
            temperature = float(temp)
            run_name = f'eval_{args.train_config}_ck{step}_temp{temp}'
            if n_samples != 4096:
                run_name += f'_n{n_samples}'
            if args.seed is not None:
                run_name += f'_s{args.seed}'
            out = os.path.join(args.out_dir, f'{run_name}.yaml')
            if os.path.exists(out) and not args.force:
                print(f'[keep] {out}')
                written.append(out)
                continue
            cfg = OmegaConf.load(base_path)
            cfg.mode = 'sample_eval'
            cfg.run_name = run_name
            if args.seed is not None:
                cfg.seed = args.seed
            cfg.eval.checkpoint_path = ckpts[step]
            # Raw weights when the run trained without EMA (`training.ema` 0), else the EMA weights
            cfg.eval.disable_ema = not (float(cfg.training.ema) > 0)
            cfg.loader.eval_batch_size = args.eval_batch_size
            cfg.sampling.num_sample_batches = args.num_sample_batches
            cfg.sampling.temperature = temperature
            header = (
                f'# {run_name}: sample_eval of {args.train_config} checkpoint-{step} ({ckpts[step]}) at sampling\n'
                f'# temperature {temperature}. Generated by scripts/make_ar_eval_configs.py from configs/'
                f'{args.train_config}.yaml: only mode,\n'
                f'# run_name, eval.checkpoint_path, sampling.temperature, sampling.num_sample_batches and '
                f'loader.eval_batch_size differ.\n'
                f'# {"Raw" if cfg.eval.disable_ema else "EMA"} weights, {args.num_sample_batches} x '
                f'{args.eval_batch_size} = {n_samples} samples, '
                f'single process. Launch bare: python -m main --config-name {run_name}\n'
            )
            with open(out, 'w') as f:
                f.write(header)
                f.write(OmegaConf.to_yaml(cfg, resolve=False))
            print(f'[write] {out}')
            written.append(out)
    names = ' '.join(os.path.basename(w)[:-5] for w in written)
    print(f'\n{len(written)} configs.')
    print('ALL:', names)


if __name__ == '__main__':
    main()
